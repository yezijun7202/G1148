// funció que retorna l'any de naixement de l'usuari
int calcular_any_naixement(int edat_actual);
int calcular_any_doble_edat(int edat_actual);

int calcular_any_naixement(int edat_actual){
	
	return (2026 - edat_actual);
}

int calcular_any_doble_edat(int edat_actual){

	return (2026 + edat_actual);

}

